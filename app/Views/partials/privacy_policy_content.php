  <section class="fu-pp-section">
    <h2 class="fu-pp-heading">I. INTRODUCTION</h2>
    <p>This Data Privacy Policy is established by Foundation University in accordance with the Data Privacy Act of 2012, which aims to safeguard the fundamental human right of every individual to privacy while ensuring the free flow of information for innovation, growth, and national development.</p>
    <p>The Data Privacy Act of 2012 defines personal information as any information, whether recorded in material form or not, from which the identity of an individual is apparent or can be reasonably and directly ascertained by the entity holding the information, or which, when combined with other information, would directly and certainly identify an individual.</p>
    <p><strong>Sensitive personal information</strong> refers to personal information:</p>
    <ol class="fu-pp-list">
      <li>About an individual’s race, ethnic origin, marital status, age, color, and religious, philosophical, or political affiliations;</li>
      <li>About an individual’s health, education, genetic or sexual life, or any proceeding for an offense committed or alleged to have been committed by such individual, the disposition of such proceedings, or the sentence of any court in such proceedings;</li>
      <li>Issued by government agencies that are specific to an individual, including but not limited to social security numbers, past or current health records, licenses or their denial, suspension or revocation, and tax returns; and</li>
      <li>Specifically classified as such by an executive order or an act of Congress.</li>
    </ol>
    <p><strong>Privileged information</strong> refers to any and all forms of data that, under the Rules of Court and other pertinent laws, constitute privileged communication.</p>
    <p><strong>Personal data</strong> refers collectively to personal information, sensitive personal information, and privileged information, whether stored in an information and communications system, a relevant filing system, or intended to form part of such systems.</p>
    <p><strong>Data subject</strong> refers to an individual whose personal information is processed.</p>
    <p>The University is a higher educational institution committed to respecting the privacy rights of its community and to protecting information collected from each individual, in accordance with the Data Privacy Act.</p>
  </section>

  <section class="fu-pp-section">
    <h2 class="fu-pp-heading">II. COVERAGE</h2>
    <p>This Privacy Policy shall apply to all departments, colleges, and offices of the University, including all units that collect, store, or process personal data in the performance of their functions and services.</p>
  </section>

  <section class="fu-pp-section">
    <h2 class="fu-pp-heading">III. PURPOSE OF PROCESSING PERSONAL DATA</h2>
    <p>The University uses students’ personal data to pursue its legitimate interests as an educational institution. This includes a range of academic, administrative, research, historical, safety, and statistical purposes, to the extent permitted or required by law. Personal data may be used for purposes such as:</p>
    <ul class="fu-pp-alpha-list">
      <li><strong>a.</strong> Enrolment and admissions;</li>
      <li><strong>b.</strong> Processing of grades;</li>
      <li><strong>c.</strong> Maintaining transcripts of records;</li>
      <li><strong>d.</strong> Processing permits for student activities on and off campus;</li>
      <li><strong>e.</strong> Capturing entry and exit logs using biometrics, turnstiles, or any other technology at designated university access points.;</li>
      <li><strong>f.</strong> Gathering data for statistical and research purposes;</li>
      <li><strong>g.</strong> Processing scholarship grants for qualified students;</li>
      <li><strong>h.</strong> Publication in official university platforms (e.g., digital magazines, student publications, university website, social media, public advisories, yearbooks);</li>
      <li><strong>i.</strong> Managing alumni records;</li>
      <li><strong>j.</strong> Coordinating with law enforcement agencies regarding security and safety concerns;</li>
      <li><strong>k.</strong> Coordinating with private and public health institutions;</li>
      <li><strong>l.</strong> Sharing graduates’ information with prospective employers.</li>
    </ul>
  </section>

  <section class="fu-pp-section">
    <h2 class="fu-pp-heading">IV. PROCESSING OF PERSONAL DATA</h2>
    <p>The University gathers, generates, receives, and uses personal data in various forms. These include photographs, videos, sound recordings, electronically transmitted data, and written records. The nature of this information may vary depending on how it is collected, its type, intended purpose, and the duration for which it is needed.</p>

    <h3 class="fu-pp-subheading">a. Admission Process</h3>
    <p>Personal data collected during the admission process include, but are not limited to, the following:</p>
    <ul class="fu-pp-list">
      <li>Name</li>
      <li>Age</li>
      <li>Citizenship</li>
      <li>Residence</li>
      <li>Date of Birth</li>
      <li>Place of Birth</li>
      <li>Religious Affiliation</li>
      <li>Phone Number</li>
      <li>Email Address</li>
      <li>Previous School Records</li>
      <li>Medical Records</li>
    </ul>
    <p>This information is gathered either through the online enrollment system or by submitting a completed enrollment form to the Registrar’s Office.</p>

    <h3 class="fu-pp-subheading">b. Student Residency Period</h3>
    <p>While enrolled at Foundation University, personal data may be collected through various departments and offices. This includes, but is not limited to:</p>
    <ul class="fu-pp-list">
      <li>Academic records and performance (e.g., attendance, grades)</li>
      <li>CCTV recordings and photographs taken within campus premises</li>
      <li>Entry and exit logs captured using biometrics, turnstiles, or any other technology at designated university access points.</li>
      <li>Membership in student organizations</li>
      <li>Disciplinary records or involvement in incidents</li>
      <li>Participation in university-sanctioned co-curricular activities</li>
      <li>Attendance in seminars, workshops, and outreach activities</li>
    </ul>

    <h3 class="fu-pp-subheading">c. Third-Party Information</h3>
    <p>Personal information released to the University by third parties may be used for educational purposes, student welfare, and other legitimate interests of the University. Non-essential information shall be properly disposed of to ensure the protection of the student’s privacy.</p>
  </section>

  <section class="fu-pp-section">
    <h2 class="fu-pp-heading">V. STORAGE</h2>
    <p>Personal Data is stored in a variety of databases, media, and formats. While the University is actively digitizing its records through the Management Information System, many units and offices still maintain paper-based records. The following units and offices may retain personal data, such as:</p>
    <ul class="fu-pp-list">
      <li>Management Information Systems Department</li>
      <li>Records of the Registrar’s Office</li>
      <li>Records of the Business and Finance Office</li>
      <li>Alumni Records</li>
      <li>Creative Department</li>
      <li>
        Digital Files, including but not limited to:
        <ul class="fu-pp-alpha-list fu-pp-sublist">
          <li><strong>i.</strong> University Event Photos</li>
          <li><strong>ii.</strong> Yearbook Photos</li>
          <li><strong>iii.</strong> College and Department Activity Photos</li>
          <li><strong>iv.</strong> Layouts, Graphics, and Animation Files</li>
          <li><strong>v.</strong> Social Media Files</li>
          <li><strong>vi.</strong> Promotional Videos</li>
          <li><strong>vii.</strong> Facebook Live Videos</li>
          <li><strong>viii.</strong> Interview Videos</li>
          <li><strong>ix.</strong> Digital Magazine and Newspaper Files</li>
        </ul>
      </li>
      <li>Colleges, Departments, and Offices</li>
      <li>Health and Medical Records</li>
      <li>Guidance Evaluation Records</li>
    </ul>
    <p>The retention periods for these records vary depending on the function and regulatory requirements of each office. For example, transcripts of records are considered permanent and are retained indefinitely, as required by law. In contrast, information collected for temporary purposes is securely disposed of once it is no longer necessary.</p>
    <p>All University units that store or handle personal data are required to implement physical, technical, and organizational safeguards. These measures are designed to ensure the secure storage of personal data and to restrict access and usage exclusively to authorized personnel for legitimate purposes.</p>
  </section>

  <section class="fu-pp-section">
    <h2 class="fu-pp-heading">VI. SHARING OF INFORMATION</h2>
    <p>The University shares personal information in accordance with the law, limited to educational, administrative, research, safety, and statistical purposes. This includes, but is not limited to, the following:</p>
    <ul class="fu-pp-alpha-list">
      <li><strong>a.</strong> References for prospective employers</li>
      <li><strong>b.</strong> Determination of student awards</li>
      <li><strong>c.</strong> Evaluation of scholarship eligibility</li>
      <li><strong>d.</strong> Requirements mandated by the Commission on Higher Education (CHED) and the Department of Education (DepEd)</li>
      <li><strong>e.</strong> Requirements mandated by the Bureau of Immigration for foreign students</li>
      <li><strong>f.</strong> Documentation of student activities and university events</li>
      <li><strong>g.</strong> University promotions (digital media, print media, social media, website)</li>
      <li><strong>h.</strong> Public advisories and news articles</li>
      <li><strong>i.</strong> Inter-office memorandums</li>
      <li><strong>j.</strong> Requirements associated with national conventions or workshop organizers</li>
      <li><strong>k.</strong> Subpoenas issued for court compliance</li>
      <li><strong>l.</strong> Safety and security purposes</li>
    </ul>
  </section>

  <section class="fu-pp-section">
    <h2 class="fu-pp-heading">VII. RIGHTS OF DATA SUBJECT</h2>
    <p>As the Data Subject, you are afforded the following rights:</p>
    <ul class="fu-pp-alpha-list">
      <li><strong>a.</strong> Be informed whether personal information pertaining to him or her shall be, are being or have been processed;</li>
      <li>
        <strong>b.</strong> Be furnished the information indicated hereunder before the entry of his or her personal information into the processing system of the personal information controller, or at the next practical opportunity:
        <ul class="fu-pp-list fu-pp-sublist">
          <li>Description of the personal information to be entered into the system;</li>
          <li>Purposes for which they are being or are to be processed;</li>
          <li>Scope and method of the personal information processing;</li>
          <li>The recipients or classes of recipients to whom they are or may be disclosed;</li>
          <li>Methods utilized for automated access, if the same is allowed by the data subject, and the extent to which such access is authorized;</li>
          <li>The identity and contact details of the personal information controller or its representative;</li>
          <li>The period for which the information will be stored; and</li>
          <li>The existence of their rights, i.e., to access, correction, as well as the right to lodge a complaint before the Commission.</li>
        </ul>
      </li>
      <li>
        <strong>c.</strong> Reasonable access to, upon demand, the following:
        <ul class="fu-pp-list fu-pp-sublist">
          <li>Contents of his or her personal information that were processed;</li>
          <li>Sources from which personal information were obtained;</li>
          <li>Names and addresses of recipients of the personal information;</li>
          <li>Manner by which such data were processed;</li>
          <li>Reasons for the disclosure of the personal information to recipients;</li>
          <li>Information on automated processes where the data will or likely to be made as the sole basis for any decision significantly affecting or will affect the data subject;</li>
          <li>Date when his or her personal information concerning the data subject were last accessed and modified; and</li>
          <li>The designation, or name or identity and address of the personal information controller;</li>
        </ul>
      </li>
      <li><strong>d.</strong> Dispute the inaccuracy or error in the personal information and have the personal information controller correct it immediately and accordingly, unless the request is vexatious or otherwise unreasonable. If the personal information have been corrected, the personal information controller shall ensure the accessibility of both the new and the retracted information and the simultaneous receipt of the new and the retracted information by recipients thereof: Provided, That the third parties who have previously received such processed personal information shall he informed of its inaccuracy and its rectification upon reasonable request of the data subject;</li>
      <li><strong>e.</strong> Suspend, withdraw or order the blocking, removal or destruction of his or her personal information from the personal information controller’s filing system upon discovery and substantial proof that the personal information are incomplete, outdated, false, unlawfully obtained, used for unauthorized purposes or are no longer necessary for the purposes for which they were collected. In this case, the personal information controller may notify third parties who have previously received such processed personal information; and</li>
      <li><strong>f.</strong> Be indemnified for any damages sustained due to such inaccurate, incomplete, outdated, false, unlawfully obtained or unauthorized use of personal information.</li>
    </ul>
  </section>

